// Helper to construct lyric lines with accurate word-level karaoke timing
function makeLyricLine(timeSec: number, text: string, highlightEmoji: string, wordsDuration = 2.5) {
  const wordsArray = text.split(' ').filter(Boolean);
  const wordTimeSpan = wordsDuration / Math.max(1, wordsArray.length);
  const words = wordsArray.map((w, i) => ({
    word: w,
    startSec: Number((timeSec + i * wordTimeSpan).toFixed(2)),
    endSec: Number((timeSec + (i + 1) * wordTimeSpan).toFixed(2)),
  }));
  return {
    timeSec,
    endSec: Number((timeSec + wordsDuration).toFixed(2)),
    text,
    highlightEmoji,
    words,
  };
}

